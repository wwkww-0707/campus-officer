def match_major(department: str) -> MajorProfile:
    """按专业名匹配画像，未命中返回通用画像。

    匹配策略：关键词子串命中即算匹配（如「计算机科学与技术」命中「计算机」），
    多个命中时取关键词最长的那个（更具体）。
    """
    if not department:
        return _GENERIC

    best: MajorProfile | None = None
    best_len = 0
    for p in _PROFILES:
        for kw in p.keywords:
            if kw in department and len(kw) > best_len:
                best, best_len = p, len(kw)
    return best or _GENERIC


def list_major_names() -> list[str]:
    """列出已内置画像的专业名（供文档与调试）。"""
    return [p.name for p in _PROFILES]


def grade_stage(grade: str) -> str:
    """从「2024级」这类年级推断当前学年阶段（大一~大四）。

    按 4 年制、9 月入学推算；无法解析时返回空串。
    """
    import datetime as _dt
    import re as _re

    m = _re.search(r"(20\d{2})", grade or "")
    if not m:
        return ""
    enroll_year = int(m.group(1))
    now = _dt.date.today()
    # 学年从当年 9 月起算：9 月之后算新学年
    academic_year = now.year - enroll_year + (1 if now.month >= 9 else 0)
    mapping = {1: "大一", 2: "大二", 3: "大三", 4: "大四"}
    return mapping.get(max(1, min(4, academic_year)), "")
