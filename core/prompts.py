# 规则引擎降级时使用的意图模板（无 LLM 也能给出合理回复）
MOCK_INTENT_HINTS = {
    "courses": "课程目录查询",
    "enrollments": "已选课程查询",
    "conflict": "时间冲突检测",
    "eligibility": "奖助学金资格初筛",
    "policy": "政策条款检索",
    "deadline": "截止时间查询",
    "enroll": "选课提交",
    "artifact": "产出物生成",
}


def build_tool_error_hint(tool_name: str, error: str) -> str:
    """根据工具名与错误信息，给出面向用户的处置建议。"""
    if "无法连接" in error or "后端" in error:
        return (
            "教务业务后端当前不可用。请先在项目目录运行 `python backend/main.py` "
            "（或直接运行 `start.bat`）启动后端，然后重试。"
        )
    if tool_name == "write_artifact":
        return "产出物写入被拒绝时，请检查文件名是否包含非法字符或路径分隔符。"
    return f"工具 `{tool_name}` 调用失败，请检查后端服务状态后重试。"
